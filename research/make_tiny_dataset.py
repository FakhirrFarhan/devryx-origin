"""Create a tiny rights-clean dataset drawn by code (shapes + captions).

Every image is generated by this script, so provenance is simple: created by
the Devryx Origin project, no external sources, no licenses needed.
"""
import json
import random
from pathlib import Path

from PIL import Image, ImageDraw

random.seed(42)
OUT = Path(__file__).parent / "data" / "tiny_shapes"
IMG = OUT / "images"
IMG.mkdir(parents=True, exist_ok=True)

COLORS = {
    "red": (214, 69, 65),
    "blue": (66, 103, 214),
    "green": (72, 178, 105),
    "amber": (232, 168, 56),
}
SHAPES = ["circle", "square", "triangle"]

rows = []
i = 0
for color_name, rgb in COLORS.items():
    for shape in SHAPES:
        for _ in range(3):
            i += 1
            size = 128
            im = Image.new("RGB", (size, size), (24, 24, 30))
            d = ImageDraw.Draw(im)
            cx, cy = size // 2 + random.randint(-14, 14), size // 2 + random.randint(-14, 14)
            r = random.randint(26, 40)
            if shape == "circle":
                d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=rgb)
            elif shape == "square":
                d.rectangle([cx - r, cy - r, cx + r, cy + r], fill=rgb)
            else:
                d.polygon([(cx, cy - r), (cx - r, cy + r), (cx + r, cy + r)], fill=rgb)
            name = f"{i:06d}.png"
            im.save(IMG / name)
            rows.append({"file": f"images/{name}", "caption": f"A {color_name} {shape} on a dark background"})

with open(OUT / "captions.jsonl", "w", encoding="utf-8") as f:
    for row in rows:
        f.write(json.dumps(row) + "\n")

print(f"Wrote {len(rows)} images to {OUT}")
