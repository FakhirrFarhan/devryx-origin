"""Dataset v0.4: breadth scale-up of the rights-clean code-drawn shapes set.

10,000 images at 64x64 (10 colors x 8 shapes). Over v0.3:
  - 10 colors (was 4) and 8 shapes (was 3): circle, square, triangle, star,
    hexagon, ring, diamond, pentagon.
  - ~80% single-object images (8,000 = 80 combos x 100), caption
    "A {color} {shape} on a dark background".
  - ~20% two-object images (2,000) with two non-overlapping shapes of
    different colors, caption
    "A {color1} {shape1} and a {color2} {shape2} on a dark background".
Shapes appear anywhere in frame, backgrounds and fills jittered like v0.3
(fill jitter kept small so the dominant color stays the named color).
Every image is generated by this script: created by the Devryx Origin
project, no external sources, no licenses needed.
"""
import json
import math
import random
from pathlib import Path

from PIL import Image, ImageDraw

random.seed(456)
OUT = Path(__file__).parent / "data" / "tiny_shapes4"
IMG = OUT / "images"
IMG.mkdir(parents=True, exist_ok=True)

SIZE = 64
COLORS = {
    "red": (214, 69, 65),
    "blue": (66, 103, 214),
    "green": (72, 178, 105),
    "amber": (232, 168, 56),
    "purple": (147, 92, 200),
    "pink": (232, 110, 180),
    "orange": (232, 126, 48),
    "white": (235, 235, 235),
    "cyan": (64, 190, 205),
    "brown": (146, 102, 66),
}
SHAPES = ["circle", "square", "triangle", "star",
          "hexagon", "ring", "diamond", "pentagon"]
PER_COMBO = 100          # 80 combos x 100 = 8,000 single-object images
PAIRS = 2000             # + 2,000 two-object images = 10,000 total


def _poly(cx, cy, r, n, rot=-math.pi / 2):
    return [(cx + r * math.cos(rot + 2 * math.pi * k / n),
             cy + r * math.sin(rot + 2 * math.pi * k / n))
            for k in range(n)]


def _star(cx, cy, r):
    pts = []
    for k in range(10):
        rad = r if k % 2 == 0 else r * 0.45
        a = -math.pi / 2 + math.pi * k / 5
        pts.append((cx + rad * math.cos(a), cy + rad * math.sin(a)))
    return pts


def draw_shape(d, shape, cx, cy, r, fill, bg):
    if shape == "circle":
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill)
    elif shape == "square":
        d.rectangle([cx - r, cy - r, cx + r, cy + r], fill=fill)
    elif shape == "triangle":
        d.polygon([(cx, cy - r), (cx - r, cy + r), (cx + r, cy + r)], fill=fill)
    elif shape == "star":
        d.polygon(_star(cx, cy, r), fill=fill)
    elif shape == "hexagon":
        d.polygon(_poly(cx, cy, r, 6, rot=0.0), fill=fill)
    elif shape == "ring":
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill)
        ri = max(2, int(r * 0.55))
        d.ellipse([cx - ri, cy - ri, cx + ri, cy + ri], fill=bg)
    elif shape == "diamond":
        d.polygon([(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)],
                  fill=fill)
    elif shape == "pentagon":
        d.polygon(_poly(cx, cy, r, 5), fill=fill)
    else:
        raise ValueError(f"unknown shape {shape}")


def jitter(rgb, amt=12):
    return tuple(max(0, min(255, c + random.randint(-amt, amt))) for c in rgb)


def place(r, taken):
    """Find a center for a shape of radius r that does not overlap the
    (cx, cy, r) shapes already in `taken`. Returns (cx, cy)."""
    for _ in range(100):
        cx = random.randint(r + 2, SIZE - r - 2)
        cy = random.randint(r + 2, SIZE - r - 2)
        if all((cx - x) ** 2 + (cy - y) ** 2 > (r + tr + 4) ** 2
               for x, y, tr in taken):
            return cx, cy
    # Fallback (extremely unlikely at these sizes): shrink into a corner.
    return r + 2, r + 2


rows = []
i = 0

# --- Single-object images (80%) ---
for color_name, rgb in COLORS.items():
    for shape in SHAPES:
        for _ in range(PER_COMBO):
            i += 1
            bg = tuple(random.randint(16, 34) for _ in range(3))
            im = Image.new("RGB", (SIZE, SIZE), bg)
            d = ImageDraw.Draw(im)
            r = random.randint(8, 27)
            cx, cy = place(r, [])
            draw_shape(d, shape, cx, cy, r, jitter(rgb), bg)
            name = f"{i:06d}.png"
            im.save(IMG / name)
            rows.append({"file": f"images/{name}",
                         "caption": f"A {color_name} {shape} on a dark background"})

# --- Two-object images (20%) ---
color_names = list(COLORS)
for _ in range(PAIRS):
    i += 1
    bg = tuple(random.randint(16, 34) for _ in range(3))
    im = Image.new("RGB", (SIZE, SIZE), bg)
    d = ImageDraw.Draw(im)
    c1, c2 = random.sample(color_names, 2)
    s1, s2 = random.sample(SHAPES, 2)
    taken = []
    parts = []
    for cname, shape in ((c1, s1), (c2, s2)):
        r = random.randint(8, 17)
        cx, cy = place(r, taken)
        taken.append((cx, cy, r))
        draw_shape(d, shape, cx, cy, r, jitter(COLORS[cname]), bg)
        parts.append(f"a {cname} {shape}")
    name = f"{i:06d}.png"
    im.save(IMG / name)
    caption = "A " + " and ".join([parts[0][2:], parts[1]]) + \
        " on a dark background"
    rows.append({"file": f"images/{name}", "caption": caption})

with open(OUT / "captions.jsonl", "w", encoding="utf-8") as f:
    for row in rows:
        f.write(json.dumps(row) + "\n")

singles = sum(1 for r in rows if " and a " not in r["caption"])
print(f"Wrote {len(rows)} images to {OUT} "
      f"({singles} single-object, {len(rows) - singles} two-object)")
