"""Dataset v0.3: scale-up of the rights-clean code-drawn shapes dataset.

1,200 images (4 colors x 3 shapes x 100). Over v0.2: shapes appear anywhere
in frame (not just near-center), wider size range, slight background and
fill jitter — the model must learn color+shape, not memorize 96 pictures.
Every image is generated by this script: created by the Devryx Origin
project, no external sources, no licenses needed.
"""
import json
import random
from pathlib import Path

from PIL import Image, ImageDraw

random.seed(123)
OUT = Path(__file__).parent / "data" / "tiny_shapes3"
IMG = OUT / "images"
IMG.mkdir(parents=True, exist_ok=True)

COLORS = {
    "red": (214, 69, 65),
    "blue": (66, 103, 214),
    "green": (72, 178, 105),
    "amber": (232, 168, 56),
}
SHAPES = ["circle", "square", "triangle"]
PER_COMBO = 100

rows = []
i = 0
for color_name, rgb in COLORS.items():
    for shape in SHAPES:
        for _ in range(PER_COMBO):
            i += 1
            size = 128
            bg = tuple(random.randint(16, 34) for _ in range(3))
            im = Image.new("RGB", (size, size), bg)
            d = ImageDraw.Draw(im)
            r = random.randint(16, 54)
            cx = random.randint(r + 4, size - r - 4)
            cy = random.randint(r + 4, size - r - 4)
            fill = tuple(max(0, min(255, c + random.randint(-12, 12))) for c in rgb)
            if shape == "circle":
                d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill)
            elif shape == "square":
                d.rectangle([cx - r, cy - r, cx + r, cy + r], fill=fill)
            else:
                d.polygon([(cx, cy - r), (cx - r, cy + r), (cx + r, cy + r)], fill=fill)
            name = f"{i:06d}.png"
            im.save(IMG / name)
            rows.append({"file": f"images/{name}", "caption": f"A {color_name} {shape} on a dark background"})

with open(OUT / "captions.jsonl", "w", encoding="utf-8") as f:
    for row in rows:
        f.write(json.dumps(row) + "\n")

print(f"Wrote {len(rows)} images to {OUT}")
